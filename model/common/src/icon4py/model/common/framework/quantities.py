"""
The quantities of the model.

A tag has a `standard_name` only where the CF standard name table has one,
otherwise `standard_name=None` and a `long_name` that describes what the field
is.
Some standard names are not in the CF table, e.g. `normal_velocity`,
`specific_cloud_content`, `virtual_potential_temperature`, ....

NOTE: temporary, replaced in part 03 (dims):
The tags are named `<Quantity>On<Place>`, as icon4py names its fields
(`theta_v_at_cells_on_half_levels`).
A 0-d quantity (`dims=()`) has no place suffix.
"""

from typing import Final

from gt4py import next as gtx

from icon4py.model.common import dimension as dims
from icon4py.model.common.quantity import Quantity, Tendency


# NOTE: temporary, replaced in part 03 (dims): the place and the precision move to the field
# type (`Field[Q, D, T]`), so `ThetaVOnCellK` and `ThetaVOnCellKHalf` become one quantity at two
# places.
CELL: Final[tuple[gtx.Dimension, ...]] = (dims.CellDim,)
CELL_K: Final[tuple[gtx.Dimension, ...]] = (dims.CellDim, dims.KDim)
CELL_KHALF: Final[tuple[gtx.Dimension, ...]] = (dims.CellDim, dims.KHalfDim)
EDGE_K: Final[tuple[gtx.Dimension, ...]] = (dims.EdgeDim, dims.KDim)
EDGE_KHALF: Final[tuple[gtx.Dimension, ...]] = (dims.EdgeDim, dims.KHalfDim)

